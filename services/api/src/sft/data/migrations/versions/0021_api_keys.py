"""Tenant API keys (#215; data model 2.1; authn and authz 5, 7.1).

Revision 0021, after 0020 (received files, #213). Expand only (data model 7): the table is
new and empty, so the code of the revisions in `compatible_with` never reads it, and its indexes
are built in the same transaction, not `CONCURRENTLY`. Renumbering it (when another revision lands
first) changes only `revision`, `down_revision` and the file name.

- `api_keys`: one row per key. Only the SHA-256 of the whole key is stored (`key_hash`, unique),
  with `key_prefix` (`sft_<env>_` and the secret's first 8 characters) so an admin recognises it.
  `created_by` is the admin who owns it, through the composite key to `users`. Scopes are chosen
  at creation and never change; a key expires at most 365 days after it was made. `revoked_reason`
  says why it ended early: an admin revoked it, or its owner was deactivated or demoted.
  `last_used_at` moves at most once an hour, and `expiry_notice` records the last expiry email the
  daily job asked for (14 or 3 days before), so a job run twice never asks again.
- `sft_api` reads, creates, revokes and touches keys in the tenant's scope, and finds one by its
  hash through `lookup_api_key`, which returns the key's ID and tenant only (data model 4.2). The
  request then continues in that tenant's scope, where the service checks expiry, revocation, the
  owner and the tenant.
- `sft_jobs` finds keys close to expiry across tenants in system scope (IDs, times and the notice
  only) and records the notice in each key's tenant scope (#215's daily step).
- `sft_notify` reads a key's prefix, owner and expiry to write the expiry and first-export emails;
  never its hash or name.
- Audited (FR-27): a key's creation and its revocation. `last_used_at` and `expiry_notice` aren't
  actions, so the trigger watches `revoked_at` only; every use writes `api_key.used` anyway.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies, lookup and
trigger were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

