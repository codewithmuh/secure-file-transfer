"""Tenant single sign-on: proven domains, the tenant's provider, just-in-time members (#231; FR-26;
data model 2.1; authn and authz 2.4, 2.5, 7.1, 7.3).

Revision 0029, after 0028 (notice windows, #230): the first of M6, whose revisions run 0029 to 0033.
Expand only (data model 7): new tables, columns with defaults, an index on a table with a few rows,
grants and policies, so the code of the revisions in `compatible_with` still runs on this schema.

- **`tenants`**: `sso_required`, the admin who confirmed that the identity provider enforces MFA
  and when (`sso_mfa_confirmed_by`, `sso_mfa_confirmed_at`, both or neither), and `sso_jit`, whether
  a first SSO sign-in creates the member. A tenant admin changes them (`updateTenantSso`), so
  `sft_api` may update those columns; `sft_operator` already updates the table
  (`configureTenantSso`).
- **`idp_connections`**: one SSO provider per tenant (a unique index on `tenant_id` where it is
  set). `sft_operator` writes the tenant's row and `sft_api` reads it, both in the tenant's scope
  only: the pools' rows have no tenant, so `tenant_isolation` never reaches them.
- **`sso_domains`**: a tenant's claimed email domains, each with the token it publishes in a DNS
  TXT record. Proven (`verified_at`), a domain is the tenant's alone: a unique index on `domain`
  where it is proven, so a pending claim never blocks another tenant. `sft_api` claims, proves and
  removes them; `sft_operator` links proven ones to the connection; `sft_scan` and `sft_jobs`, which
  run the DLP decision, read the proven ones as trusted recipient domains (FR-45). Sign-in finds the
  connection of a proven domain through `lookup_sso_domain`, which returns IDs, the provider's name
  and its status, never a token.
- **`sso_group_roles`**: identity provider groups that give a member created just in time a role.
- **`user_identities`**: `sft_api` now binds an SSO subject to a user at sign-in (just in time).
- Audited (FR-27): every change to the new tables, by their audit triggers; `tenants` and
  `idp_connections` have had theirs since revisions 0001 and 0006.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies, lookup and
triggers were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

