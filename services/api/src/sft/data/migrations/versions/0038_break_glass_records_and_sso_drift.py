BREAK_GLASS_TENANTS_BODY = (
    "SELECT coalesce((SELECT g.tenant_ids FROM public.break_glass_grants g "
    "WHERE g.id = CAST(nullif(current_setting('app.break_glass_grant', true), '') AS uuid) "
    "AND g.state = 'active' AND g.recorded_by = 'service' "
    "AND g.starts_at <= now() AND g.ends_at > now()), "
    "CAST('{}' AS uuid[]))"
)
