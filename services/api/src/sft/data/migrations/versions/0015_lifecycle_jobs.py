"""The lifecycle jobs: expiry, deletion, reconciliation and the daily cleanup (#181; data model 3.1,
5, 6; architecture 4.5).

Revision 0015, after 0014 (download grants, #180). Expand only (data model 7): the code of the
revisions in `compatible_with` must still run on this schema. Renumbering it (when another revision
lands first) changes only `revision`, `down_revision` and the file name.

- `files.deleted_at`: when the deletion job removed every object version of the file. A `deleted`
  file has it, a check added `NOT VALID` and validated in its own transaction.
- **The jobs' finds** (data model 5): partial indexes for the expiry job, abandoned drafts,
  abandoned uploads, stuck completions and the deletion job, built `CONCURRENTLY` outside the
  migration's transaction, as revision 0010 built the scan sweep's.
- **What `sft_jobs` may do** (data model 4.2, authn and authz 7.3). It finds due work across
  tenants in system scope (`jobs_find`, read only) and acts on each item in that item's tenant
  scope, under `tenant_isolation`:
  - transfers: record `expired`, and cancel a draft after 7 days, with `ended_at`;
  - files: the columns of a deletion (`delete_after`, `deleted_at`, the state), of completion's
    phases 2 and 3, which reconciliation runs again for a file left `completing`, and of a
    rejection; never `display_name_ct`;
  - `tenant_usage`: release a file's reservation when it is deleted;
  - `verification_codes`, `link_sessions`, `download_grants`: delete expired rows (the daily
    cleanup), and set a grant's `archived_at` once reconciliation has rewritten its committed
    record. It reads only the columns those need.
- Still no delete of a `files`, `transfers` or `transfer_recipients` row by any role: the metadata
  purge after 365 days arrives with its own issue. The API's role is granted no `DELETE` here.

Like every revision, it keeps the literal SQL it runs. The grants and policies were generated with
`sft.data.rls` when it was written; tests/test_migrations.py checks that they still match.
"""

