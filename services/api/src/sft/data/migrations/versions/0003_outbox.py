"""The transactional outbox and the processed-message records (ADR-0013, data model 2.5).

Expand only (data model 7): the code of the revisions in `compatible_with` must still run on this
schema. Renumbering it (when another revision lands first) changes only `revision`,
`down_revision` and the file name. Both tables are new and empty, so their indexes
are built in the same transaction, not `CONCURRENTLY`.

Like every revision, it keeps the literal SQL it runs; the grants and policies were generated with
`sft.data.rls` when it was written, and tests/test_migrations.py checks that they still match.
"""

import sqlalchemy as sa
from alembic import op
from sqlalchemy.dialects import postgresql

revision = "0003"
down_revision = "0002"
branch_labels = None
depends_on = None

# The earlier revisions whose code still runs on this schema: the previous head's code never reads
# these tables.
compatible_with: tuple[str, ...] = (down_revision,)

# Every workload that changes state and hands work on writes in its tenant's scope: the API, the
# operator API (a new tenant's first admin is invited), the scan worker (a transfer's evaluation,
# and deferred scans, abuse and rate limits 6.4) and the lifecycle jobs (the daily run). Nobody else
# may read the rows. The relay reads and marks every tenant's rows, in system scope only (authn and
# authz 7.3); SELECT … FOR UPDATE needs both of its policies. Generated by
# tenant_rls_sql("outbox", grants={"sft_api": "INSERT", "sft_operator": "INSERT",
# "sft_scan": "INSERT", "sft_jobs": "INSERT"}), then grant_sql("outbox", "sft_relay",
# "SELECT, UPDATE") and policy_sql for relay_read (SELECT) and relay_mark (UPDATE), each with
# app_scope() = 'system'.
OUTBOX_RLS = (
    "ALTER TABLE outbox ENABLE ROW LEVEL SECURITY",
    "GRANT INSERT ON outbox TO sft_api",
    "GRANT INSERT ON outbox TO sft_operator",
    "GRANT INSERT ON outbox TO sft_scan",
    "GRANT INSERT ON outbox TO sft_jobs",
    "CREATE POLICY tenant_isolation ON outbox FOR ALL TO sft_api, sft_operator, sft_scan, sft_jobs "
    "USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id())",
    "GRANT SELECT, UPDATE ON outbox TO sft_relay",
    "CREATE POLICY relay_read ON outbox FOR SELECT TO sft_relay USING (app_scope() = 'system')",
    "CREATE POLICY relay_mark ON outbox FOR UPDATE TO sft_relay "
    "USING (app_scope() = 'system') WITH CHECK (app_scope() = 'system')",
)

# The consumers record with INSERT … ON CONFLICT DO NOTHING, which needs no SELECT: a consumer
# learns that a message is a duplicate from the row count, and reads nothing back. Generated by
# tenant_rls_sql("processed_messages", grants={"sft_scan": "INSERT", "sft_notify": "INSERT"}).
PROCESSED_MESSAGES_RLS = (
    "ALTER TABLE processed_messages ENABLE ROW LEVEL SECURITY",
    "GRANT INSERT ON processed_messages TO sft_scan",
    "GRANT INSERT ON processed_messages TO sft_notify",
    "CREATE POLICY tenant_isolation ON processed_messages FOR ALL TO sft_scan, sft_notify "
    "USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id())",
)


def upgrade() -> None:
    # One row per message, written in the transaction of the change that causes it (architecture
    # 5.3). No foreign key to tenants: like audit events, plumbing rows outlive what they name.
    op.create_table(
        "outbox",
        sa.Column("id", sa.Uuid, primary_key=True),
        sa.Column("tenant_id", sa.Uuid, nullable=False),
        sa.Column("topic", sa.Text, nullable=False),
        # IDs only (ADR-0013, threat model T-49); sft.data.outbox refuses anything else.
        sa.Column("payload", postgresql.JSONB, nullable=False),
        sa.Column(
            "trace_context",
            postgresql.JSONB,
            server_default=sa.text("'{}'::jsonb"),
            nullable=False,
        ),
        # The message may be received no earlier than created_at + delay_seconds: the relay sends
        # it with the part of the delay that is left as SQS's DelaySeconds, at most 15 minutes.
        sa.Column("delay_seconds", sa.Integer, server_default=sa.text("0"), nullable=False),
        sa.Column(
            "created_at", sa.DateTime(timezone=True), server_default=sa.func.now(), nullable=False
        ),
        sa.Column("published_at", sa.DateTime(timezone=True), nullable=True),
        # Failed sends, and when the relay may try again: each row backs off on its own, so one
        # message SQS keeps refusing can't hold up the rows behind it.
        sa.Column("attempts", sa.Integer, server_default=sa.text("0"), nullable=False),
        sa.Column(
            "next_attempt_at",
            sa.DateTime(timezone=True),
            server_default=sa.func.now(),
            nullable=False,
        ),
        # The error code of the last failed send, such as `AccessDenied`; never a message body.
        sa.Column("last_error", sa.Text, nullable=True),
        sa.CheckConstraint("delay_seconds BETWEEN 0 AND 900", name="outbox_delay_seconds_check"),
        sa.CheckConstraint("attempts >= 0", name="outbox_attempts_check"),
        sa.CheckConstraint("jsonb_typeof(payload) = 'object'", name="outbox_payload_check"),
        sa.CheckConstraint(
            "jsonb_typeof(trace_context) = 'object'", name="outbox_trace_context_check"
        ),
    )
    # The relay's claim and the outbox age metric (data model 5).
    op.create_index(
        "outbox_unpublished_idx",
        "outbox",
        ["created_at"],
        postgresql_where=sa.text("published_at IS NULL"),
    )
    for statement in OUTBOX_RLS:
        op.execute(statement)

    # Makes every consumer idempotent (ADR-0013): one row per message a consumer has handled,
    # written in the same transaction as the handler's effects. For work queues `message_id` is the
    # outbox row's ID; intake queues use their source's event ID, so it is text. Every message
    # belongs to a tenant, so the consumer records it in that tenant's scope.
    op.create_table(
        "processed_messages",
        sa.Column("consumer", sa.Text, nullable=False),
        sa.Column("message_id", sa.Text, nullable=False),
        sa.Column("tenant_id", sa.Uuid, nullable=False),
        sa.Column(
            "processed_at",
            sa.DateTime(timezone=True),
            server_default=sa.func.now(),
            nullable=False,
        ),
        sa.PrimaryKeyConstraint("consumer", "message_id", name="processed_messages_pkey"),
    )
    for statement in PROCESSED_MESSAGES_RLS:
        op.execute(statement)


def downgrade() -> None:
    # Deploys and rollbacks never run a down-migration (ADR-0005).
    raise NotImplementedError
