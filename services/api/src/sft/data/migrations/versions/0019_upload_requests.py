"""Upload requests, and the uploader's codes, link sessions and link lookups (#212; UC-2, FR-10,
FR-14, FR-15, NFR-14; data model 2.2, 2.4, 3.3, 4.2, 5).

Revision 0019, after 0018 (the first-download notice, #214). Expand only (data model 7): the code
of the revisions in `compatible_with` must still run on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- **`upload_requests`** (data model 2.2, states in 3.3): one uploader per request, every column of
  2.2. `message_ct` holds the message as `sft.service.fields` seals it; `link_token_hash` is unique,
  with `link_key_id` and `link_issued_at` set together or not at all, as for recipients;
  `failed_attempts`, `locked_at` and `unlocked_by` are the lockout of 2.4; `purge_after` stays
  empty until the purge job exists. A new, empty table: its keys and indexes are built in the
  migration's transaction. Indexes (data model 5): the unique link hash, audit search by address,
  and the expiry job's partial index on open requests.
- **`verification_codes` and `link_sessions` belong to a recipient or an upload request** (data
  model 2.4): each gains `upload_request_id` with a composite foreign key that cascades, its
  `recipient_id` becomes nullable, and a check says exactly one is set. Both tables hold rows, so
  the check and the key are added `NOT VALID` and validated in transactions of their own, and the
  new columns' indexes are built `CONCURRENTLY` first (data model 7).
- **The link lookups learn the upload request** (data model 4.2). `lookup_link_token` and
  `lookup_link_sessions` keep their signatures for the code of `compatible_with`, so two new
  functions answer for both subjects: `lookup_link_subject` (a recipient or an upload request by
  `link_token_hash`) and `lookup_link_subject_sessions` (sessions with their recipient or upload
  request). `lookup_link_sessions` is replaced, same signature, to return recipients' sessions only:
  the older code builds a recipient from every row it gets, so an uploader's session must never
  reach it. Replacing a function takes its owner, so the revision becomes `sft_lookup` for that one
  statement, with `CREATE` on `public` only while it does (as `lookup_function_sql` hands a new
  function over), then `sft_owner` again.
- **Grants** (authn and authz 7.3), generated with `sft.data.rls`: the API reads, creates and
  changes requests. The notification worker (`sft_notify`) reads the uploader's address, locale,
  link and status with the request's owner, state and expiry, never `message_ct`, and writes the
  link and the delivery state; it also reads a code's `upload_request_id`, to supersede the older
  codes. The expiry job (`sft_jobs`) finds open requests past `expires_at` across tenants
  (`jobs_find`), records `expired` with `ended_at`, and ends their link sessions (`revoked_at`).
  `sft_lookup` reads the columns of its lookups only.
- Audited (FR-27): every change to a request commits with an audit event (`audit_required`).
  `verification_codes` and `link_sessions` keep their triggers.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies, lookups and the
trigger were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

