"""Audit events: the partitioned table, its policies, partition upkeep and the fail-closed trigger.

Revision 0002, after 0001. Expand only (data model 7): the code of the revisions in
`compatible_with` must still run on this schema.

- `audit_events` (data model 2.5), partitioned by month on `occurred_at`, with a `DEFAULT`
  partition and the partitions of this month and the next three (data model 6).
- Grants and policies of authentication and authorization 7.2 and 7.3: workload roles insert in
  their scope and never update or delete; `sft_api` reads its tenant's events; `sft_archive` reads
  every event in system scope; `sft_recovery` re-imports archived events in recovery scope. No
  role is granted a partition.
- `audit_create_partitions(months_ahead)` and `audit_partition_status()`, for the lifecycle job
  (`sft_jobs`).
- `audit_required()`, the trigger function behind `sft.data.audit_required`, attached to
  `tenants`: creating or suspending a tenant commits only with its audit event (FR-27, FR-34).

Like every revision, it keeps the literal SQL it runs. The grants, policies and trigger were
generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_audit_catalog.py checks that they still match.
"""

