    # Monthly partitions, ahead of time (data model 6). The lifecycle job calls this daily as
    # sft_jobs. Months are whole UTC months. A partition is created on its own, then attached:
    # attaching locks only the new table and the default partition, so inserts into the other
    # months never wait for it. A month whose rows already sit in the default partition is
    # skipped and reported as `blocked`: moving them out is an operator's decision, and the
    # alert on the default partition stays on until then.
    op.execute(
        """
        CREATE FUNCTION audit_create_partitions(months_ahead integer DEFAULT 3)
            RETURNS TABLE (partition_name text, status text)
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, public
            SET lock_timeout = '2s'
            AS $$
        DECLARE
            this_month timestamp := date_trunc('month', now() AT TIME ZONE 'UTC');
            month_start timestamptz;
            month_end timestamptz;
        BEGIN
            IF months_ahead IS NULL OR months_ahead NOT BETWEEN 0 AND 12 THEN
                RAISE EXCEPTION 'months_ahead must be between 0 and 12'
                    USING ERRCODE = 'invalid_parameter_value';
            END IF;
            FOR i IN 0 .. months_ahead LOOP
                month_start := (this_month + make_interval(months => i)) AT TIME ZONE 'UTC';
                month_end := (this_month + make_interval(months => i + 1)) AT TIME ZONE 'UTC';
                partition_name := 'audit_events_' || to_char(month_start AT TIME ZONE 'UTC',
                                                             '"y"YYYY"m"MM');
                IF to_regclass(partition_name) IS NOT NULL THEN
                    status := 'exists';
                ELSIF EXISTS (SELECT FROM audit_events_default
                               WHERE occurred_at >= month_start AND occurred_at < month_end) THEN
                    status := 'blocked';
                ELSE
                    EXECUTE format('CREATE TABLE public.%I (LIKE public.audit_events '
                                   'INCLUDING DEFAULTS INCLUDING CONSTRAINTS)', partition_name);
                    EXECUTE format('ALTER TABLE public.audit_events ATTACH PARTITION public.%I '
                                   'FOR VALUES FROM (%L) TO (%L)',
                                   partition_name, month_start, month_end);
                    status := 'created';
                END IF;
                RETURN NEXT;
            END LOOP;
        END
        $$
        """
    )
    # What the alerts watch (data model 6): rows in the default partition, and how many months
    # from this one on have a partition, without a gap. After the job has run it is 4.
    op.execute(
        """
        CREATE FUNCTION audit_partition_status()
            RETURNS TABLE (default_rows bigint, months_covered integer)
            LANGUAGE plpgsql STABLE SECURITY DEFINER
            SET search_path = pg_catalog, public
            AS $$
        DECLARE
            this_month timestamp := date_trunc('month', now() AT TIME ZONE 'UTC');
            found regclass;
        BEGIN
            SELECT count(*) INTO default_rows FROM audit_events_default;
            months_covered := 0;
            LOOP
                found := to_regclass('audit_events_' || to_char(
                    this_month + make_interval(months => months_covered), '"y"YYYY"m"MM'));
                EXIT WHEN found IS NULL OR NOT EXISTS (
                    SELECT FROM pg_inherits
                     WHERE inhrelid = found AND inhparent = 'audit_events'::regclass);
                months_covered := months_covered + 1;
            END LOOP;
            RETURN NEXT;
        END
        $$
        """
    )
