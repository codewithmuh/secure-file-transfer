# Authentication and authorization 7.2 and 7.3. Workload roles insert in their scope and never
# update or delete. They may not set `tx_id` or `occurred_at`: their INSERT grant leaves both
# out, so the database's defaults always apply and an event can't be backdated or pinned on
# another transaction. Only sft_recovery, re-importing archived events with their original
# values in recovery scope (data model 4.2), may set them. sft_api reads its tenant's events in
# tenant scope only: a link session's resource scope carries the tenant too, and a recipient must
# never read the audit log (FR-28). Events are inserted in tenant or resource scope (a
# recipient's download, a verification attempt), or with no tenant in platform scope, never
# through `IS NOT DISTINCT FROM`, which would accept a row from a transaction that forgot its
# tenant (ADR-0020). sft_archive reads every event in system scope. Generated by grant_sql and
# policy_sql (tests/test_audit_catalog.py lists the calls).
