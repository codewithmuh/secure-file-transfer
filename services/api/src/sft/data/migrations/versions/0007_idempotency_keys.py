"""Idempotency keys: what a creating `POST` did, so a retry gets the same answer (architecture 5.4).

Revision 0007, after 0006 (data model 2.5, API README 5, #144). Expand only (data model 7): the
code of the revisions in `compatible_with` must still run on this schema. The table is new and
empty, so its index is built in the same transaction. Renumbering it (when another revision lands
first) changes only `revision`, `down_revision` and the file name.

- `idempotency_keys`: one row per caller and key, for 24 hours. The primary key is
  `(caller_type, caller_id, key)`: a key is the caller's own, so two callers can't collide.
  `request_fingerprint` is the SHA-256 of the method, the path with its resource IDs and the
  canonical body. The row keeps the status and a reference to what was created, never a response
  body, so no secret, address, file name or message is stored here.
- Written by `sft_api` in the tenant's scope, in the same transaction as what it records. An
  expired row of the same key is overwritten (`UPDATE`), so a key can be used again a day later
  before the daily job has run.
- The daily job, as `sft_jobs`: it finds the tenants with expired rows in system scope (`jobs_find`
  reads two columns there), then deletes each tenant's expired rows in that tenant's scope.
- Not audited: remembering a request isn't an action. The change it records is audited in the same
  transaction (`NOT_AUDITED`).

Like every revision, it keeps the literal SQL it runs. The key, grants and policies were generated
with `sft.data.rls` when it was written; tests/test_migrations.py checks that they still match.
"""

