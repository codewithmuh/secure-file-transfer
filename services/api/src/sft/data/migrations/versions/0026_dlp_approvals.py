"""DLP approvals: approval requests and the approvers' decisions (#220, DLP-5; data model 2.7, 3.2,
3.6, 5, 6; architecture 4.6; threat model T-100, T-104).

Revision 0026, after 0025 (the DLP decision, #219). Expand only (data model 7): the code of the
revisions in `compatible_with` must still run on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- `dlp_approval_requests`: a sender's request for approval of a decision that needs one (FR-43),
  with the confirmation that carries the justification. States of data model 3.6; `ended_at` is
  set exactly when the request leaves `pending`. One pending request per transfer (a partial
  unique index, so two at once can't both commit); at most 3 per transfer, which the service
  counts under the transfer's row lock. `expires_at` is the earlier of the request time plus the
  tenant's `approval_timeout` and the transfer's own `expires_at`.
- `dlp_approval_decisions`: one approver's approval or rejection of a request, unique per approver
  and request, so one approver counts once (FR-44). A rejection needs a comment. `comment_ct` is
  sealed with the field stand-in of M2 (`sft.service.fields`); `data_key_version` stays empty
  until M6.
- Both go with their transfer (`ON DELETE CASCADE` through the request), so the purge job deletes
  them with the rest (data model 6).
- **Who may do what.** `sft_api` reads and writes both, and may change only a request's `state`
  and `ended_at`. The `expiry` job (`sft_jobs`) finds pending requests past `expires_at` across
  tenants in system scope (`jobs_find`) and ends them in each tenant's scope; it reads no
  justification, comment or decision. The notification worker (`sft_notify`) reads a request's
  transfer and state, to email the approvers and the sender (FR-43).
- Audited: every insert, update and delete of both tables needs its event (NFR-15).

The partial index on `users (tenant_id) WHERE dlp_approver AND status = 'active'` that finds the
eligible approvers exists since revision 0004.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies and triggers
were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

