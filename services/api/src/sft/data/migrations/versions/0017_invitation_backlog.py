"""The notification worker finds the members left `invited` before the user pool existed (#193;
authn and authz 2.5).

Revision 0017, after 0016 (pool identities, #197). Expand only (data model 7): one policy, so the
code of the revisions in `compatible_with` still runs on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- **The invitation backlog pass** (`python -m sft.workers.notify invite-backlog`, run once when an
  environment's user pool first exists) lists, across tenants, the users still `invited`: in the
  system scope, read only, as the lifecycle jobs find their work. It then works in each user's
  tenant scope, as before: it skips a user who already has an identity on the pool's connection,
  and writes a new `member.invited` message for the rest. The worker already may read `users`
  (revision 0004); this adds no grant, only the rows the system scope sees.
- Nothing is written in the system scope; `users` keeps its audit trigger (revision 0004).

Like every revision, it keeps the literal SQL it runs. The policy was generated with `sft.data.rls`
when it was written; tests/test_migrations.py checks that it still matches.
"""

