SINGLE_REGION = """
    CREATE TABLE audit_archive_single_region (
        generation integer NOT NULL,
        from_tx xid8 NOT NULL,
        up_to_tx xid8 NOT NULL,
        region text NOT NULL,
        archived_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT audit_archive_single_region_pkey PRIMARY KEY (generation, from_tx),
        CONSTRAINT audit_archive_single_region_range_check CHECK (up_to_tx > from_tx),
        CONSTRAINT audit_archive_single_region_region_check
            CHECK (region IN ('ap-northeast-1', 'ap-northeast-3'))
    )
"""

