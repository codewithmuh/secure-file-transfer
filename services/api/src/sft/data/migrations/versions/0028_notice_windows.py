"""Notice windows: the coalesced DLP policy notice, the approvers' digest and the cap on the "no
eligible approver" notices (#230; FR-43, FR-54; abuse and rate limits 7.1; data model 2.5, 5).

Revision 0028, after 0027 (DLP-6 and DLP-7, #221 and #222). Expand only (data model 7): the code of
the revisions in `compatible_with` must still run on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- **`notice_windows`**: one row per tenant and kind of notice, and per approver for the digest,
  which the notification worker keeps (`sft.data.notice_windows`). `notice` names the kind:
  `dlp_policy_changed` (the kinds of change waiting in `changes`, the latest at `changed_at`, the
  coalesced email due at `due_at`), `dlp_approval_digest` (one approver's `user_id`, the emails
  `sent` in the hour since `window_started_at`, the digest due at `due_at`) and
  `dlp_no_eligible_approver` (the emails `sent` since `window_started_at`, capped). Unique on
  `(tenant_id, notice, user_id)` with nulls not distinct, so a tenant has one row of each kind and
  an approver one digest row; a check keeps `user_id` to the digest. A new, empty table: its keys
  and indexes are built in the migration's transaction.
- **Who may do what.** Only the notification worker (`sft_notify`) reads and writes it, in its
  tenant's scope. Nothing deletes a row: a tenant has at most two, plus one per approver.
- **Not audited** (`sft.data.audit_required.NOT_AUDITED`): a window is bookkeeping of the emails
  about changes that were audited when they were made, and every email it sends is audited
  (`email.sent`).

Like every revision, it keeps the literal SQL it runs. The keys, grants and policies were generated
with `sft.data.rls` when it was written; tests/test_migrations.py checks that they still match.
"""

