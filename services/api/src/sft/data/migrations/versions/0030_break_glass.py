"""Break-glass in the service: two-person grants and a database role that ends with them (#232;
FR-35; data model 2.6; authn and authz 7.3, 8.3).

Revision 0030, after 0029 (tenant SSO, #231). Expand only (data model 7): a new table, a function,
grants and policies, so the code of the revisions in `compatible_with` still runs on this schema.

- **`break_glass_grants`**: a platform table (no tenant, no row-level security), granted to
  `sft_operator` alone, as `operator_sessions` is. An operator asks (`requestBreakGlass`), a second
  operator approves (`approveBreakGlass`), and the grant is `active` from then until `ends_at`, at
  most an hour. The columns of the Identity Center path (`assignment_request_id`, `recorded_by`,
  `review_due_at`, `review_url`, data model 2.6) are here too, for `recordBreakGlassGrant`.
- **`sft_breakglass`** (created by the bootstrap job, `sft.data.roles.BREAK_GLASS`) reads the rows
  of a grant's tenants in `tenants`, `users`, `transfers`, `transfer_recipients`, `files`,
  `upload_requests` and `audit_events`, and nothing else: `SELECT` only, through `break_glass_read`
  policies on `break_glass_tenants()`. That function returns the `tenant_ids` of the grant named by
  the session's `app.break_glass_grant`, and only while it is `active` and before its `ends_at`:
  access ends on time whether or not anyone acts, and a grant that ends early ends it with the
  transaction. File names and messages are ciphertext to this role (encryption and keys 4).
- The function runs as the owner, reads one row by its key, pins its `search_path` and may be run
  by `sft_breakglass` alone.

Like every revision, it keeps the literal SQL it runs. The grants and policies were generated with
`sft.data.rls` when it was written; tests/test_migrations.py checks that they still match.
"""

