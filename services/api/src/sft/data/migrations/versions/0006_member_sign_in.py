"""Member sign-in: connections, identities and member sessions (data model 2.1, 2.4; ADR-0016).

Revision 0006, after 0005. Expand only (data model 7): the code of the revisions in
`compatible_with` must still run on this schema. The tables are new and empty, so their indexes
are built in the same transaction, not `CONCURRENTLY`. Renumbering it (when another revision lands
first) changes only `revision`, `down_revision` and the file name.

- `idp_connections`: one row per user pool (no tenant) and, from M6, one per tenant SSO provider.
  `provider_name` is unique; `issuer` is recorded but never used to find a row (data model 2.1).
  No workload is granted it yet: sign-in reads it only through `lookup_idp_connection`, and the
  operator API writes it with its own grants when it configures SSO (M6).
- `user_identities`: `(idp_connection_id, subject)` is unique, and maps a sign-in to its user. It
  refers to its connection by ID alone, because a pool's connection has no tenant (data model 2);
  to its user through the composite key. Sign-in reads it only through `lookup_user_identity`; the
  notification worker and the SSO invitation flow write it with grants of their own, later.
- `member_sessions`: the API's server-side sessions (authn and authz 3.2). Only the SHA-256 of the
  256-bit token is stored. `identity_id` names the identity by ID only, so a sign-in reset can
  delete identities while their revoked sessions remain until the daily cleanup (data model 2).
  `sft_api` reads, creates, touches and revokes sessions in the tenant's scope, and finds one by
  its hash through `lookup_member_session`, which returns its IDs and whether it is live, so an
  ended session is told apart from a token no session ever had (abuse and rate limits 2.2, H).
  `sft_operator` may only revoke them, in the tenant's scope, when it suspends the tenant: it
  reads two columns and writes the two of a revocation (authn and authz 3.3).
- Audited (FR-27): every change to connections and identities, and a session's creation and
  revocation. Moving `last_seen_at` isn't an action, so the trigger watches `revoked_at` only.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies, lookups and
triggers were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

