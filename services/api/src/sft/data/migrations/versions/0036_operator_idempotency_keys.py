"""Idempotency keys for the operator API (#160; architecture 5.4, API README 5, authn-authz 8.2).

Revision 0036, after 0035. Expand only (data model 7): a wider check, grants and policies, so the
code of the revisions in `compatible_with` still runs on this schema.

`createTenant` and `recoverTenantAdmin` keep their `Idempotency-Key` in `idempotency_keys`, the
table of every other creating operation, in the scope of the tenant they make or act on, so the key
commits with the change it records:

- **The owner** is the operator, not their 15-minute token: `caller_type = 'operator'` and
  `caller_id` a UUID derived from their Identity Center user name (`sft.service.idempotency`), so a
  retry with a new token still finds the key.
- **`operator_keys`**: `sft_operator` reads and writes its own keys (`caller_type = 'operator'`) in
  the tenant's scope, and nobody else's.
- **`operator_find`**: before `createTenant` makes a tenant, it looks for the key across tenants,
  in platform scope: the operator keys only, which hold a fingerprint, a status and the tenant's
  ID, never a body. That is the third read across tenants the operator API makes, after the tenant
  directory (revision 0005) and the drift check's connections (#239); it changes nothing.
- The primary key `(caller_type, caller_id, key)` spans tenants, so a key the operator used for
  one tenant can't be written again for a second: a race of two retries ends with one tenant.
- The daily job deletes expired operator keys as it does the others (`sft_jobs`, revision 0007).

Like every revision, it keeps the literal SQL it runs. The grants and policies were generated with
`sft.data.rls` when it was written; tests/test_migrations.py checks that they still match.
"""

