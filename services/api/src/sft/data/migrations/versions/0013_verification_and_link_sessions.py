"""Verification codes, link sessions and the link credential lookups (#179; data model 2.4, 4.2;
authn and authz 4).

Revision 0013, after 0012 (recipients' links, #178). Expand only (data model 7): the code of the
revisions in `compatible_with` must still run on this schema. Both tables are new and empty, so
their indexes are built in the same transaction, not `CONCURRENTLY`. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- `verification_codes` (data model 2.4): a code's HMAC under the `code-hmac` keyring (never the
  code), its key version, a 10-minute expiry and at most 5 attempts. The notification worker
  (`sft_notify`) creates a code and supersedes the older ones of its recipient; it may read only
  the columns that takes, never an HMAC. The API reads codes and counts attempts.
- `link_sessions` (data model 2.4, authn and authz 4.3): a verified browser's session, as the
  SHA-256 of its 256-bit token, 24 hours at most. The API creates, reads, touches and revokes them.
- **The recipient key only.** Each table refers to its recipient, `NOT NULL`, through a composite
  foreign key that cascades. The upload-request key and the check that exactly one owner is set
  arrive with upload requests (M5), as revision 0008 did for `files`.
- **Credential lookups** (data model 4.2): `lookup_link_token` finds a recipient by its link's
  token hash, `lookup_link_sessions` up to 10 sessions by their hashes from one cookie. Each
  returns IDs and a status, never a hash; only `sft_api` may run them, in lookup scope.
- Audited (FR-27): every code row change (its creation, each attempt, its use or supersession)
  and a session's start and end. Moving `last_seen_at` isn't an action, so the sessions' trigger
  watches `revoked_at` only, as for member sessions.

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies, lookups and
triggers were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

