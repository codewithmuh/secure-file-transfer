"""Field encryption: the tenants' field data keys (#236; encryption and keys 3.2, 7.2; data model
2.1, 6; ADR-0017).

Revision 0031, after 0030 (break-glass, #232). Expand only (data model 7): the code of the
revisions in `compatible_with` still runs on this schema. It writes format 0 values with no key
version, which every new key allows.

- `tenant_data_keys`: each version of a tenant's field data key, as KMS returned it wrapped under
  the fields key with the encryption context `purpose = field-dek` and the tenant. Never the key.
  At most one version is live (`retired_at` empty, a partial unique index) and takes new writes;
  a retired version only decrypts, until no row uses it. The API creates version 1 with the
  first value it seals for the tenant; the primary key settles a race.
- **The ciphertext columns name their key version.** `files`, `transfers`, `upload_requests`,
  `dlp_confirmations` and `dlp_approval_decisions` get a composite foreign key
  `(tenant_id, data_key_version) → tenant_data_keys`, so the database refuses to delete a version
  a row still uses (data model 2.1). A new key on an existing table: the referencing columns are
  indexed `CONCURRENTLY` where no index exists yet, each key is added `NOT VALID`, then validated
  in a transaction of its own. Every existing row has no version, so validation finds nothing.
- **The field key job** (`sft.workers.field_keys`) runs as the API's workload, the only one that
  may unwrap a field data key (encryption and keys 4.3): it re-seals the format 0 rows of M2's
  stand-in (the backfill), rotates, re-wraps and purges key versions. It finds the tenants
  through `field_key_tenants`, a lookup function that returns tenant IDs only, and acts in each
  tenant's scope. `sft_api` may now also update the justification and the comment columns, for
  the backfill and the re-encryption only.
- **Who may do what.** `sft_api` reads, inserts and deletes key versions and may change only
  `wrapped_key` (a re-wrap) and `retired_at`. No other role reaches the table: the scan worker,
  the notification worker, the jobs and the operator API never unwrap a field data key.
- Not audited (`sft.data.audit_required.NOT_AUDITED`): a version is created with the first value
  sealed under it, in a transaction whose change is audited; the job writes its own events for
  every rotation, re-wrap and purge.

Like every revision, it keeps the literal SQL it runs. The grants, policies and lookup function
were generated with `sft.data.rls` when it was written; tests/test_field_keys.py checks that they
still match.
"""

