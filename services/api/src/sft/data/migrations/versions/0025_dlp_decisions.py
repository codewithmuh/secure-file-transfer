# A recipient's domain, from the address the API stored (sft.data.transfers.insert_recipients):
# everything after the one `@`. An invoker trigger function with its path pinned.
DOMAIN_FUNCTION = """
CREATE FUNCTION transfer_recipients_domain() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
    NEW.domain := split_part(NEW.email_normalized, '@', -1);
    RETURN NEW;
END
$$
"""
DOMAIN_TRIGGER = (
    "CREATE TRIGGER transfer_recipients_domain BEFORE INSERT OR UPDATE OF email_normalized "
    "ON transfer_recipients FOR EACH ROW EXECUTE FUNCTION transfer_recipients_domain()"
)
DOMAIN_BACKFILL = (
    "UPDATE transfer_recipients SET domain = split_part(email_normalized, '@', -1) "
    "WHERE domain IS NULL"
)


