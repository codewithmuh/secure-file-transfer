"""The DLP decision of a transfer: decisions, the rules they matched, confirmations and the
tenant's known recipient domains (#219, DLP-4; data model 2.2, 2.7, 3.2, 5, 6; architecture 4.6).

Revision 0025, after 0024 (the DLP policy, #218). Expand only (data model 7): the code of the
revisions in `compatible_with` must still run on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- `dlp_decisions`: one row per decision, never updated. Exactly one of `transfer_id` (a transfer's
  evaluation) and `file_id` (a received file's inspection, FR-51, #221) is set. It records the
  policy version, the mode, the outcome, whether it was enforced (false only in monitor mode) and
  how many recipients were untrusted and how many recipient domains new, never which.
- `dlp_decision_rules`: the rules a decision matched, each with the revision it applied and the
  count that crossed its threshold. Its key to `dlp_rules (tenant_id, id, revision)` has no
  `ON DELETE`, so a revision a decision refers to can't be deleted: the daily cleanup skips it.
- `dlp_confirmations`: the sender's confirmation of a decision (FR-42), and later the
  justification of an approval request (FR-43, #220). `justification_ct` is sealed with the field
  stand-in of M2 (`sft.service.fields`).
- `dlp_known_domains`: the recipient domains the tenant has sent to, written when a transfer moves
  to `sent` (FR-46); the daily cleanup deletes a domain 365 days after `last_sent_at`.
- `transfers.dlp_decision_id`: the transfer's current decision (revision 0008 named it for DLP-5;
  it belongs here). A new foreign key on an existing table (data model 7): the column is indexed
  `CONCURRENTLY`, the key added `NOT VALID`, then validated in a transaction of its own.
- `transfer_recipients.domain`: the domain part of `email_normalized`, set by a trigger on every
  insert (and backfilled here), so the evaluation's system roles, which never read an address
  (revision 0009), can tell trusted and new domains apart. Code that predates it needn't set it.
- Children of a transfer (its decisions, their rules and its confirmations) go with it
  (`ON DELETE CASCADE`), so the purge job deletes them with the rest (data model 6).
- **Who may do what** (T-107). The evaluation runs as `sft_api` (a send or a file removal),
  `sft_scan` (a scan result) and `sft_jobs` (the scan sweep, reconciliation): each may insert
  decisions and decision rules, set `transfers.dlp_decision_id`, read the recipients' domains and
  the findings' counts (never `detail_ct`), and insert or update known domains. `sft_api` also
  reads decisions and inserts and reads confirmations. `sft_jobs` deletes known domains and reads
  which rule revisions decisions name, finding both across tenants in system scope (`jobs_find`).
- Audited: every insert, update and delete of the four tables needs its event (NFR-15).

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies and triggers
were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

