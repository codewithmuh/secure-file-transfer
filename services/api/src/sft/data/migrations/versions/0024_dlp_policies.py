def _text_array(values: tuple[str, ...]) -> str:
    return "ARRAY[" + ", ".join(f"'{v}'" for v in values) + "]::text[]"


def _quoted(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


_ROWS = ",\n    ".join(
    f"({n}, {_quoted(en)}, {_quoted(ja)}, '{condition}', {_text_array(detectors)}, "
    f"'{confidence}', {threshold}, {_text_array(reasons)}, '{action}')"
    for n, (en, ja, condition, detectors, confidence, threshold, reasons, action) in enumerate(
        DEFAULT_RULES
    )
)

DEFAULT_POLICY_FUNCTION = f"""
CREATE FUNCTION dlp_default_policy(p_tenant_id uuid, p_created_by uuid, p_locale text)
RETURNS void LANGUAGE sql VOLATILE SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp AS $$
WITH policy AS (
    INSERT INTO public.dlp_policies (tenant_id) VALUES (p_tenant_id)
    ON CONFLICT (tenant_id) DO NOTHING RETURNING tenant_id
)
INSERT INTO public.dlp_rules (id, revision, tenant_id, name, direction, condition, detectors,
                              min_confidence, threshold, reasons, recipient_scope, action,
                              created_by)
SELECT encode(set_bit(set_bit(overlay(uuid_send(gen_random_uuid()) PLACING
           substring(int8send(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint + r.n)
           FROM 3) FROM 1 FOR 6), 52, 1), 53, 1), 'hex')::uuid,
       1, policy.tenant_id, CASE WHEN p_locale = 'ja' THEN r.name_ja ELSE r.name_en END, 'sent',
       r.condition, r.detectors, r.min_confidence, r.threshold, r.reasons, 'any', r.action,
       p_created_by
  FROM policy CROSS JOIN (VALUES
    {_ROWS}
  ) AS r (n, name_en, name_ja, condition, detectors, min_confidence, threshold, reasons, action);
$$
"""  # noqa: S608 - the literal DEFAULT_RULES above, no input

