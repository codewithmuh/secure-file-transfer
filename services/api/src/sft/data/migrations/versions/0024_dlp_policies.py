"""The tenant's DLP policy, rules and own detectors, and the default policy of every tenant (#218,
DLP-4; data model 2.7, 5, 6; detectors 5, 6; ADR-0022).

Revision 0024, after 0023 (domain rules, #217). Expand only (data model 7): the code of
the revisions in `compatible_with` must still run on this schema. Renumbering it (when another
revision lands first) changes only `revision`, `down_revision` and the file name.

- `dlp_policies`: one row per tenant, its mode, `version`, trusted domains (at most 500,
  lowercase) and approval timeout (1 hour to 7 days). `version` goes up by one in the transaction
  of every change to this row, a rule or a detector.
- `dlp_rules` and `dlp_detectors` are **revisions**: primary key `(id, revision)`, and
  `retired_at` set on the revision a change replaces, or on the last one when the rule or detector
  is deleted. A partial unique index keeps one live revision per ID, and the unique key
  `(tenant_id, id, revision)` is what a decision's rule (#219) refers to. The checks are data
  model 2.7's: a rule for `received` files only allows and records or blocks, with a `content` or
  `not_inspected` condition and scope `any`; `approvals_required = 2` only with `require_approval`;
  a `content` rule names detectors and a `not_inspected` rule names reasons. `new_domain` is a
  condition (FR-46, which the planning moved into #219, so the default policy keeps its rule).
- A detector's `definition_ct` is its keyword list (or pattern, #221) as sealed JSON. Until DLP-8
  the seal is the stand-in of M2 (`sft.service.dlp_definitions`), so `dlp_key_version` stays empty
  and has no foreign key: `tenant_dlp_keys` arrives with DLP-8.
- **The default policy** (detectors 6) is the function `dlp_default_policy(tenant, created_by,
  locale)`: the policy row at version 1 and its eight rules, named in the tenant's default
  language. The data migration runs it, as the owner, for every tenant without a policy: the
  rules' `created_by` is the tenant's earliest admin, else its earliest user, else empty.
  `createTenant` runs it as `sft_operator` in the transaction that makes the tenant, with the
  first admin it invites; the local seed runs it for its tenant. A tenant that has a policy keeps
  it: the function then writes nothing (which is why `sft_operator` may read `tenant_id`, the
  column its `RETURNING` names). Rule IDs are UUIDv7 made in SQL,
  a millisecond apart, so the rules list in the order of detectors 6. It is `SECURITY INVOKER`:
  the caller's grants, policies and the audit trigger apply as to any insert.
- **Who may do what** (data model 4.2): `sft_api` reads and writes all three, and may change only
  `retired_at` of a revision; `sft_operator` inserts a new tenant's policy and rules; `sft_scan`
  reads them (the tenant's live detectors and the policy version travel with each file to the
  inspector; the decision of #219 reads rules), never writes them; `sft_jobs` reads them (the
  scan sweep's evaluation, #219) and deletes retired revisions in the daily cleanup, which finds
  them across tenants in system scope (`jobs_find`) and checks that no finding names a detector:
  it reads `dlp_findings (tenant_id, detector)` for that, and nothing else of the table.
- Audited: every insert, update and delete of the three tables needs its event (NFR-15).

Like every revision, it keeps the literal SQL it runs. The keys, grants, policies and triggers
were generated with `sft.data.rls` and `sft.data.audit_required` when it was written;
tests/test_migrations.py checks that they still match.
"""

