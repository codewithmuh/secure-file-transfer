/** The translations, one tree per language. `i18n.test.ts` checks that both have the same keys (FR-33). */
export const resources = {
  en: { translation: en.translation },
  ja: { translation: ja.translation },
};

export type Language = keyof typeof resources;
export const LANGUAGES = Object.keys(resources) as Language[];

/**
 * The first of the browser's preferred languages the app has, else English. The recipient and uploader pages will
 * switch to the link's `locale` once they call the API (FR-33); this is the language until then.
 */
export function preferredLanguage(preferred: readonly string[]): Language {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split('-')[0];
    const match = LANGUAGES.find((language) => language === base);
    if (match) return match;
  }
  return 'en';
}

// Screen readers pick their voice from <html lang>, so it follows the language shown (WCAG 3.1.1).
i18n.on('languageChanged', (language) => {
  if (typeof document !== 'undefined') document.documentElement.lang = language;
});

void i18n.use(initReactI18next).init({
  resources,
  lng: preferredLanguage(typeof navigator === 'undefined' ? [] : navigator.languages),
  fallbackLng: 'en',
  supportedLngs: LANGUAGES,
  interpolation: {
    escapeValue: false,
  },
});

export default i18n;
